const normalizeGender = (gender) =>
  typeof gender === 'string' && gender.trim().toLowerCase() === 'female'
    ? 'female'
    : 'male';

const normalizeView = (view) => (view === 'back' ? 'back' : 'front');

const hasExerciseAnatomyImage = (exerciseId) =>
  typeof exerciseId === 'string' &&
  Object.prototype.hasOwnProperty.call(EXERCISE_ANATOMY_IMAGES, exerciseId);

const resolveExerciseAnatomyImage = (exerciseId, gender, view) => {
  const exerciseAssets = hasExerciseAnatomyImage(exerciseId)
    ? EXERCISE_ANATOMY_IMAGES[exerciseId]
    : NEUTRAL_ANATOMY_IMAGES;
  return exerciseAssets[normalizeGender(gender)][normalizeView(view)];
};

module.exports = {
  EXERCISE_ANATOMY_IMAGES,
  NEUTRAL_ANATOMY_IMAGES,
  hasExerciseAnatomyImage,
  normalizeGender,
  normalizeView,
  resolveExerciseAnatomyImage,
};

